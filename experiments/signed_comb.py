# ---------------------------------------------------------------- arithmetic

def exact_div(a, b):
    """a / b as an integer, asserted exact. Python's floor division is exact
    whenever b divides a, for either sign; the assertion is the proof."""
    assert b != 0 and a % b == 0, "inexact division %d / %d" % (a, b)
    return a // b


def v2(n):
    assert n != 0
    n = abs(n)
    v = 0
    while n % 2 == 0:
        n //= 2
        v += 1
    return v


def v3(n):
    assert n != 0
    n = abs(n)
    v = 0
    while n % 3 == 0:
        n //= 3
        v += 1
    return v


def mod3(n):
    """The residue of n mod 3 in {0,1,2}: Python's % already does this for
    negative n (-5 % 3 == 1, -7 % 3 == 2)."""
    r = n % 3
    assert r in (0, 1, 2)
    return r


def is_state(w, d):
    return w != 0 and w % 2 == 1 and w % 3 != 0 and d >= 1


def peak(w, d):
    return 3 ** d * w - 1


def exit_data(w, d):
    A = peak(w, d)
    s = v2(A)
    return A, s, exact_div(A, 2 ** s)


def state_of_odd(y):
    """Door recovery; y odd, y != -1."""
    assert y % 2 == 1 and y != -1
    n = y + 1
    m = v2(n)
    u = exact_div(n, 2 ** m)
    a = v3(u)
    return (exact_div(u, 3 ** a), m + a)


def F(w, d):
    y = exit_data(w, d)[2]
    return None if y == -1 else state_of_odd(y)


def F_via_C(w, d):
    """spine.md 5.6: C = A + 2^s, w+ = C / (2^v2(C) 3^v3(C)), d+ = v2(C) - s + v3(C)."""
    A, s, y = exit_data(w, d)
    C = A + 2 ** s
    if C == 0:
        return None
    sig, a = v2(C), v3(C)
    return (exact_div(C, 2 ** sig * 3 ** a), sig - s + a)


def doors(W, D):
    return [(a, 2 ** (D - a) * 3 ** a * W - 1) for a in range(D)]


def admissible(y, s):
    return mod3(y) != 0 and (s % 2 == 1) == (mod3(y) == 1)


def node_at(y, s):
    N = 2 ** s * y + 1
    assert N % 3 == 0, "not an admissible branch"
    d = v3(N)
    return (exact_div(N, 3 ** d), d)


def lowest_branch(y):
    return 1 if mod3(y) == 1 else 2


def parent(w, d):
    """(state, type) or None. None exactly at the nodes with s <= 2 and exit -1,
    i.e. at (-1,1); the positive root (1,1) is handled by the ring sets below."""
    A, s, y = exit_data(w, d)
    if s >= 3:
        return node_at(y, s - 2), "cascade"
    if y == -1:
        return None
    return state_of_odd(y), "door"


def children(W, D):
    A, s, y = exit_data(W, D)
    lst = [(node_at(y, s + 2), "cascade", s + 2, (v3(y + 1) if y != -1 else None, y))]
    dead, excluded = [], []
    for a, ya in doors(W, D):
        if ya % 3 == 0:
            dead.append((a, ya))
            continue
        s0 = lowest_branch(ya)
        st = node_at(ya, s0)
        if st == (W, D):
            excluded.append((a, ya, s0))
            continue
        lst.append((st, "door", s0, (a, ya)))
    return lst, dead, excluded


def top_dead(W, D):
    return (2 ** D * W) % 3 == 1


# ---------------------------------------------------------------- rings

POS = (1, 1)
SING = (-1, 1)
FIX = (-1, 2)
RING2 = [(-1, 4), (-5, 3), (-11, 1)]
RINGS = {"pos": {POS}, "sing": {SING}, "fix": {FIX}, "two": set(RING2)}
FCYC = {"pos": {POS}, "sing": set(), "fix": {FIX}, "two": {(-1, 4), (-5, 3)}}
ALL_RING = {}
for _k, _s in RINGS.items():
    for _v in _s:
        ALL_RING[_v] = _k
NAMES = {"pos": "positive root (1,1)", "sing": "singular root (-1,1)",
         "fix": "fixed state (-1,2)", "two": "2-cycle ring (-1,4),(-5,3),(-11,1)"}

CHAIN_MEMO = {}


def chain_target(w, d, cap=100000):
    """Follow the comb parent to a ring. Returns (key, lambda, door_edges, cascade_edges,
    type of the last edge into the ring, the node that edge leaves) -- for a ring node
    (key, 0, 0, 0, None, None) -- or None when the cap is hit or the chain stops
    outside every ring."""
    path, edges = [], []
    cur = (w, d)
    while cur not in ALL_RING and cur not in CHAIN_MEMO:
        if len(path) >= cap:
            return None
        p = parent(*cur)
        if p is None:
            return None
        path.append(cur)
        edges.append(p[1])
        cur = p[0]
    k, lam, de, ce, last, lastnode = (ALL_RING[cur], 0, 0, 0, None, None) if cur in ALL_RING else CHAIN_MEMO[cur]
    for i in range(len(path) - 1, -1, -1):
        lam += 1
        if edges[i] == "door":
            de += 1
        else:
            ce += 1
        if last is None:
            last, lastnode = edges[i], path[i]
        CHAIN_MEMO[path[i]] = (k, lam, de, ce, last, lastnode)
    return (k, lam, de, ce, last, lastnode)


ORBIT_MEMO = {}


def orbit_target(w, d, cap=100000):
    """Iterate F to an F-periodic ring node or to the singular exit; returns (key, eta)."""
    path = []
    cur = (w, d)
    while True:
        k = None
        for key, cyc in FCYC.items():
            if cur in cyc:
                k = key
        if k is not None:
            break
        if cur in ORBIT_MEMO:
            k, e = ORBIT_MEMO[cur]
            for i, p in enumerate(path):
                ORBIT_MEMO[p] = (k, e + len(path) - i)
            return k, e + len(path)
        if len(path) >= cap:
            return None
        nxt = F(*cur)
        if nxt is None:            # exit -1: the singular door
            k = "sing"
            break
        path.append(cur)
        cur = nxt
    for i, p in enumerate(path):
        ORBIT_MEMO[p] = (k, len(path) - i)
    return k, len(path)


def col_orbit_odd(x, n):
    """The odd values of the raw orbit of x under Col, n odd steps."""
    vals = []
    for _ in range(n):
        x = 3 * x + 1
        while x % 2 == 0:
            x //= 2
        vals.append(x)
    return vals


def S(st):
    return "(%d,%d)" % st


