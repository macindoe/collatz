# ---------------------------------------------------------------- (a) Item A

def rand_neg_state(rng, wmax, dmax):
    while True:
        w = -rng.randrange(1, wmax, 2)
        if w % 3 != 0:
            return (w, rng.randrange(1, dmax + 1))


def section_a(rng):
    out("--- (a) Item A: the signed rules on 3,000 random negative states (|w| < 10^6, d <= 40) ---")
    n0 = CHECKS
    n_exit1 = 0
    for _ in range(3000):
        w, d = rand_neg_state(rng, 10 ** 6, 40)
        A, s, y = exit_data(w, d)
        check(A < 0 and A % 2 == 0 and A + 1 == 3 ** d * w and 2 ** s * y == A and y % 2 == 1 and y < 0, "peak/exit of %s" % S((w, d)))
        check(admissible(y, s), "branch parity: s odd iff y = 1 mod 3 at %s" % S((w, d)))
        check(node_at(y, s) == (w, d), "node(y,s) recovers the state at %s" % S((w, d)))
        if y == -1:
            n_exit1 += 1
            check(F(w, d) is None and F_via_C(w, d) is None and s % 2 == 0 and (w, d) == node_at(-1, s), "exit -1 at %s" % S((w, d)))
        else:
            f = F(w, d)
            check(f == F_via_C(w, d) and is_state(*f) and f[0] < 0, "F by recovery = F by C, negative, at %s" % S((w, d)))
            a = v3(y + 1)
            check(doors(*f)[a][1] == y and f[1] - a == v2(y + 1), "the exit is door a = v3(y+1) of F(v) at %s" % S((w, d)))
        # the cascade identity and the parent
        check(node_at(y, s + 2) == (exact_div(4 * (A + 1) - 3, 3 ** v3(4 * (A + 1) - 3)), v3(4 * (A + 1) - 3)), "14.10.1 at %s" % S((w, d)))
        p = parent(w, d)
        if s >= 3:
            check(p is not None and p[1] == "cascade" and exit_data(*p[0])[1:] == (s - 2, y) and is_state(*p[0]), "cascade parent at %s" % S((w, d)))
        elif y != -1:
            check(p == (state_of_odd(y), "door"), "door parent at %s" % S((w, d)))
        if p is not None:
            lst, dead, exc = children(*p[0])
            hits = [c for c in lst if c[0] == (w, d)]
            check(len(hits) == 1 and hits[0][1] == p[1], "regenerated once by the parent's children at %s" % S((w, d)))
        # the children rule against 14.1.1 at s <= 2, and each child's parent
        lst, dead, exc = children(w, d)
        seen = set()
        for st, t, sc, dr in lst:
            check(is_state(*st) and st[0] < 0 and st not in seen, "child valid, negative, distinct at %s" % S((w, d)))
            seen.add(st)
            check(parent(*st) == ((w, d), t), "child's parent at %s" % S((w, d)))
            if t == "door":
                check(sc == lowest_branch(dr[1]) and F(*st) == (w, d) and exit_data(*st)[2] == dr[1], "door child through door %d at %s" % (dr[1], S((w, d))))
            else:
                check(exit_data(*st)[0] == 4 * A, "cascade child 4A at %s" % S((w, d)))
        live = [ya for a, ya in doors(w, d) if ya % 3 != 0]
        check(len(lst) == 1 + len(live) - len(exc) and len(dead) == (1 if top_dead(w, d) else 0), "degree 1 + D - [dead] at %s" % S((w, d)))
        check(all(ya % 3 == 2 for a, ya in doors(w, d) if a >= 1), "side doors never dead at %s" % S((w, d)))
    out("  3,000 states; %d with exit -1 (each on door -1's chain)" % n_exit1)
    # sign preservation on the positive side too
    for _ in range(1000):
        w, d = rand_neg_state(rng, 10 ** 6, 40)
        w = -w
        f = F(w, d)
        check(f is not None and f[0] > 0 and f == F_via_C(w, d), "positive stays positive at %s" % S((w, d)))
    # the singular exit: on the box |w| < 10^5, d <= 30, the states with exit -1 are exactly door -1's chain
    box_exit1 = set()
    for w in range(-1, -10 ** 5, -2):
        if w % 3 == 0:
            continue
        for d in range(1, 31):
            if exit_data(w, d)[2] == -1:
                box_exit1.add((w, d))
    chain = set()
    s = 2
    while True:
        st = node_at(-1, s)
        if abs(st[0]) >= 10 ** 5 and st[1] > 30:
            break
        if abs(st[0]) < 10 ** 5 and st[1] <= 30:
            chain.add(st)
        s += 2
        if s > 400:
            break
    check(box_exit1 == chain and SING in chain, "exit -1 on the box = door -1's chain in the box")
    out("  states with exit -1 in the box |w| < 10^5, d <= 30: %d, all on door -1's chain (branches 2..%d); at s <= 2 only (-1,1)" % (len(box_exit1), max(exit_data(*st)[1] for st in box_exit1)))
    check(all(exit_data(*st)[1] >= 4 for st in box_exit1 if st != SING), "at s <= 2 only (-1,1) exits to -1")
    # 14.1.1 against a brute-force forward scan
    targets = [(-1, 2), (-1, 4), (-5, 3), (-11, 1), (-1, 1), (-5, 1), (-7, 2), (-13, 1)]
    scan = {t: set() for t in targets}
    for w in range(-1, -3001, -2):
        if w % 3 == 0:
            continue
        for d in range(1, 13):
            f = F(w, d)
            if f in scan:
                scan[f].add((w, d))
    for t in targets:
        rule = set()
        for a, ya in doors(*t):
            if ya % 3 == 0:
                continue
            for s in range(lowest_branch(ya), 41, 2):
                st = node_at(ya, s)
                if -3000 <= st[0] <= -1 and st[1] <= 12:
                    rule.add(st)
        check(rule == scan[t], "14.1.1 predecessors of %s in the box = forward scan (%d)" % (S(t), len(scan[t])))
    out("  forward scan of (-3000 <= w <= -1, d <= 12) at eight targets: predecessor sets %s equal to 14.1.1's rule; (-1,1) has none (Garden of Eden)" % [len(scan[t]) for t in targets])
    report("(a)")


# ---------------------------------------------------------------- (b) Item B

def ring_of_cycle(cycle):
    """The comb ring of an F-cycle: each v_i with its lower siblings on its exit door."""
    ring = []
    for v in cycle:
        A, s, y = exit_data(*v)
        for j in range(s, 0, -2):
            ring.append(node_at(y, j))
    return ring


def section_b():
    out("--- (b) Item B: the three rings, the ring-length statement, the tree property on the box |w| < 10^5, d <= 30 ---")
    # the F-cycles by direct iteration
    for start, cyc in ((FIX, [FIX]), ((-1, 4), [(-1, 4), (-5, 3)]), ((-5, 3), [(-5, 3), (-1, 4)]), (POS, [POS])):
        orb = [start]
        for _ in range(len(cyc)):
            orb.append(F(*orb[-1]))
        check(orb[:-1] == cyc and orb[-1] == start, "F-cycle from %s" % S(start))
    # the parent-map cycles and the ring-length formula
    for key, cyc in (("fix", [FIX]), ("two", [(-1, 4), (-5, 3)]), ("pos", [POS])):
        ring = ring_of_cycle(cyc)
        check(set(ring) == RINGS[key] and len(ring) == len(set(ring)), "ring of %s by the sibling rule" % key)
        pred = sum(1 + (exit_data(*v)[1] - 1) // 2 for v in cyc)
        check(pred == len(RINGS[key]), "ring length = sum(1 + floor((s_i - 1)/2)) = %d for %s" % (pred, key))
        # the parent map on the ring: a cyclic permutation for p >= 2, the excluded self-loop for p = 1
        if len(cyc) >= 2:
            cur = cyc[0]
            seen = []
            for _ in range(len(ring)):
                seen.append(cur)
                cur = parent(*cur)[0]
            check(cur == cyc[0] and set(seen) == RINGS[key] and len(set(seen)) == len(ring), "parent map cycles the ring of %s" % key)
        else:
            check(parent(*cyc[0]) == (cyc[0], "door"), "the fixed state's parent is its excluded self-loop (%s)" % key)
    out("  rings: fix %s, two %s, pos %s; singular root (-1,1) with no parent" % (sorted(RINGS["fix"]), RING2, sorted(RINGS["pos"])))
    # the tree property on the box: chain target = orbit target, eps in {0,1}
    t0 = time.time()
    counts = {"sing": 0, "fix": 0, "two": 0}
    lam_max = eta_max = 0
    eps_count = {0: 0, 1: 0}
    n_box = 0
    ring_in_box = 0
    for w in range(-1, -10 ** 5, -2):
        if w % 3 == 0:
            continue
        for d in range(1, 31):
            n_box += 1
            ct = chain_target(w, d)
            ot = orbit_target(w, d)
            if not check(ct is not None and ot is not None, "chain and orbit reach a ring from %s" % S((w, d))):
                continue
            k, lam, de, ce, last, lastnode = ct
            check(k == ot[0] and k != "pos", "same component by chain and by orbit at %s" % S((w, d)))
            if (w, d) in ALL_RING:
                ring_in_box += 1
                check(lam == 0 and ot[1] == (1 if (w, d) == (-11, 1) else 0), "ring node distances at %s" % S((w, d)))
                counts[k] += 1
                continue
            counts[k] += 1
            eta = ot[1]
            eps = eta - de
            check(lam == de + ce and eps in (0, 1), "lambda = door + cascade, eta - door edges in {0,1} at %s" % S((w, d)))
            # eps = 0 iff the last edge into the ring is a door edge into an F-periodic ring node
            into = parent(*lastnode)[0]
            pred = 0 if k == "sing" else (0 if (last == "door" and into in FCYC[k]) else 1)
            check(eps == pred, "eps rule at %s (eps %d, last %s into %s)" % (S((w, d)), eps, last, S(into)))
            if k == "sing":
                check(eps == 0, "singular component: eta = door edges at %s" % S((w, d)))
            eps_count[eps] += 1
            lam_max = max(lam_max, lam)
            eta_max = max(eta_max, eta)
    out("  %d states: every parent chain reaches exactly one ring (singular %d, fixed %d, 2-cycle %d; %d ring nodes in the box), the same one its F-orbit reaches" % (n_box, counts["sing"], counts["fix"], counts["two"], ring_in_box))
    out("  largest lambda %d, largest eta %d; eta - door edges = 0 at %d states, = 1 at %d; %.1f s" % (lam_max, eta_max, eps_count[0], eps_count[1], time.time() - t0))
    out("  fractions of the box: singular %.4f, fixed %.4f, 2-cycle %.4f" % tuple(counts[k] / n_box for k in ("sing", "fix", "two")))
    report("(b)")


