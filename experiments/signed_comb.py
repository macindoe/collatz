def section_d(rng):
    out("--- (d) Item D: the fixed-state equation at s = 1, w * 3^a * (2^(d-a+1) - 3^(d-a)) = 1, d <= 60 ---")
    # the identity behind the reduction: y - y_a = (w 3^a (2^(d-a+1) - 3^(d-a)) - 1)/2 at s = 1, i.e. 2(y_a - y) = ...
    for _ in range(2000):
        w, d = rand_neg_state(rng, 10 ** 6, 40)
        if rng.randrange(2):
            w = -w
        A = peak(w, d)
        a = rng.randrange(d)
        ya = 2 ** (d - a) * 3 ** a * w - 1
        check(2 * ya - A == w * 3 ** a * (2 ** (d - a + 1) - 3 ** (d - a)) - 1, "identity 2 y_a - A = w 3^a (2^(d-a+1) - 3^(d-a)) - 1 at %s" % S((w, d)))
        f = F(w, d)
        fixed = f == (w, d)
        check(fixed == (exit_data(w, d)[2] in [y for _, y in doors(w, d)]), "F-fixed iff the exit is an own door at %s" % S((w, d)))
    sols = []
    for d in range(1, 61):
        q = 2 ** (d + 1) - 3 ** d
        if abs(q) == 1:
            w = q                       # w * q = 1 with q = +-1
            check(is_state(w, d) and exit_data(w, d)[1] == 1 and F(w, d) == (w, d) and exit_data(w, d)[2] == doors(w, d)[0][1], "fixed state at d = %d" % d)
            sols.append((w, d, q))
        else:
            check(all((w * q) != 1 for w in (1, -1)), "no unit solution at d = %d (2^(d+1) - 3^d = %d)" % (d, q))
        for a in range(1, d):
            check((3 ** a * (2 ** (d - a + 1) - 3 ** (d - a))) % 3 == 0, "a >= 1: the product is divisible by 3, never 1 (d = %d, a = %d)" % (d, a))
    check(sols == [(1, 1, 1), (-1, 2, -1)], "the two solutions: (1,1) at 4 - 3 = 1 and (-1,2) at 8 - 9 = -1")
    out("  solutions with d <= 60: %s -- (1,1) from 2^2 - 3 = 1 and (-1,2) from 2^3 - 3^2 = -1; at a >= 1 the product is a multiple of 3" % sols)
    report("(d)")


