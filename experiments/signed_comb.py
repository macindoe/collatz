ROOT_CHAIN = {"pos": (1, 1, 2), "sing": (-1, 2, 4), "fix": (-5, 1, 10), "two": (-17, 3, 136)}   # door, branch at level 0, |peak|


def census(key, levels):
    """Level-by-level enumeration from the ring, no size cutoff. Returns the per-level
    rows and the run-length tallies."""
    ring = RINGS[key]
    level = [(st, None, 0) for st in sorted(ring)]        # (state, edge in, door run)
    rows = []
    krun, drun_tally, s12 = {}, {}, {1: 0, 2: 0}
    for lam in range(levels + 1):
        n = len(level)
        casc_in = sum(1 for st, e, r in level if e == "cascade")
        door_in = sum(1 for st, e, r in level if e == "door")
        dist = {}
        maxpeak, argmax = 0, []
        sumD = ndead = sumdeg = 0
        nxt = []
        for st, e, r in level:
            A, s, y = exit_data(*st)
            dist[st[1]] = dist.get(st[1], 0) + 1
            if abs(A) > maxpeak:
                maxpeak, argmax = abs(A), [st]
            elif abs(A) == maxpeak:
                argmax.append(st)
            sumD += st[1]
            ndead += 1 if top_dead(*st) else 0
            if lam > 0:
                k = (s - 1) // 2
                krun[k] = krun.get(k, 0) + 1
                if e == "door":
                    drun_tally[r] = drun_tally.get(r, 0) + 1
                    s12[s] += 1
            lst, dead, exc = children(*st)
            for ch, t, sc, dr in lst:
                if ch in ring:
                    continue
                sumdeg += 1
                nxt.append((ch, t, (1 + r) if (t == "door" and lam > 0 and e == "door") else (1 if t == "door" else 0)))
        rows.append({"lam": lam, "n": n, "casc": casc_in, "door": door_in, "dist": dist, "maxpeak": maxpeak, "argmax": argmax,
                     "sumD": sumD, "ndead": ndead, "sumdeg": sumdeg})
        if lam < levels:
            check(len(nxt) == sumdeg and len(set(c[0] for c in nxt)) == len(nxt), "level %d of %s: children distinct, sum deg = next count" % (lam, key))
            level = nxt
    return rows, krun, drun_tally, s12


def fmt_dist(dist):
    parts = []
    for j in sorted(dist):
        if j <= 9:
            parts.append("%d:%d" % (j, dist[j]))
    big = sum(v for j, v in dist.items() if j > 9)
    if big:
        parts.append(">9:%d" % big)
    return " ".join(parts)


def print_census(key, rows):
    out("  %s" % NAMES[key])
    out("  level     nodes  cascade-in   door-in  depth distribution (d:count)                                 largest |peak|")
    for r in rows:
        out("  %5d %9d  %10d  %8d  %-58s %d" % (r["lam"], r["n"], r["casc"], r["door"], fmt_dist(r["dist"]), r["maxpeak"]))
    out("  level    nodes  mean D  dead-top  door children  mean degree  next/this   P(D=1..4)")
    for i, r in enumerate(rows):
        if r["lam"] < 16:
            continue
        n = r["n"]
        ratio = ("%9.4f" % (rows[i + 1]["n"] / n)) if i + 1 < len(rows) else "        -"
        pd = " ".join("%.4f" % (r["dist"].get(j, 0) / n) for j in range(1, 5))
        out("  %5d %8d  %.4f    %.4f         %.4f       %.4f  %s   %s" % (r["lam"], n, r["sumD"] / n, r["ndead"] / n, (r["sumdeg"] - n) / n, r["sumdeg"] / n, ratio, pd))
    out("  ledger 2/3^j                                                              0.6667 0.2222 0.0741 0.0247")


def section_c(rng):
    out("--- (c) Item C: the control census to level %d, each component beside the positive comb ---" % LEVELS)
    all_rows, all_runs = {}, {}
    for key in ("pos", "sing", "fix", "two"):
        t0 = time.time()
        rows, krun, drun_tally, s12 = census(key, LEVELS)
        dt = time.time() - t0
        all_rows[key] = rows
        all_runs[key] = (krun, drun_tally, s12)
        total = sum(r["n"] for r in rows)
        out("  [%s: %d nodes over levels 0..%d, %.1f s]" % (key, total, LEVELS, dt))
        print_census(key, rows)
        # the identities of 18.7.2 at every level, and the largest-peak law per root
        door, s_root, c = ROOT_CHAIN[key]
        for i, r in enumerate(rows):
            if i + 1 < len(rows):
                check(rows[i + 1]["n"] == r["sumdeg"], "sum deg = next level count at level %d of %s" % (r["lam"], key))
                if r["lam"] > 0:
                    # every non-ring node has degree 1 + D - [top door dead] (no self-child, no ring child)
                    check(r["sumdeg"] == r["n"] + r["sumD"] - r["ndead"], "sum deg = n + sum D - dead at level %d of %s" % (r["lam"], key))
                    check(rows[i + 1]["casc"] == r["n"], "cascade-in = previous count at level %d of %s" % (r["lam"] + 1, key))
                else:
                    ring_casc = sum(1 for st in RINGS[key] for ch in children(*st)[0] if ch[0] in RINGS[key] and ch[1] == "cascade")
                    check(rows[1]["casc"] == r["n"] - ring_casc, "cascade-in at level 1 of %s = ring size minus ring cascade children" % key)
            lam = r["lam"]
            check(r["maxpeak"] == c * 4 ** lam and r["argmax"] == [node_at(door, s_root + 2 * lam)], "largest |peak| at level %d of %s is %d on door %d" % (lam, key, c * 4 ** lam, door))
        out("  largest |peak| at level lambda: %d * 4^lambda, on door %d at branch %d + 2*lambda, at no other node (levels 0..%d)" % (c, door, s_root, LEVELS))
    # the positive census against comb.md 18.5's table
    known = [1, 1, 2, 3, 10, 17, 30, 61, 124, 239, 478, 961, 1978, 3823, 7748, 15597, 30844, 61947, 124068, 247507, 495986]
    check([r["n"] for r in all_rows["pos"]][:21] == known[:LEVELS + 1], "positive census equals comb.md 18.5 to level 20")
    # side by side: the level counts
    out("  level counts side by side (pos / sing / fix / two) and the ratio to the positive count")
    for i in range(LEVELS + 1):
        ns = [all_rows[k][i]["n"] for k in ("pos", "sing", "fix", "two")]
        out("  %5d %9d %9d %9d %9d   %.4f %.4f %.4f" % (i, ns[0], ns[1], ns[2], ns[3], ns[1] / ns[0], ns[2] / ns[0], ns[3] / ns[0]))
    # the run-length table, census populations side by side, and the negative box
    out("  own cascade run k = floor((s-1)/2), fraction over the census nodes at levels 1..%d (pos / sing / fix / two), box |w| < 10^5, d <= 30 (negative), ledger (3/4)4^-k" % LEVELS)
    box_k, box_run, box_s12 = {}, {}, {1: 0, 2: 0}
    nbox = 0
    for w in range(-1, -10 ** 5, -2):
        if w % 3 == 0:
            continue
        for d in range(1, 31):
            nbox += 1
            A, s, y = exit_data(w, d)
            k = (s - 1) // 2
            box_k[k] = box_k.get(k, 0) + 1
            if s <= 2:
                box_s12[s] += 1
                n = 1
                cur = (w, d)
                while True:
                    cur = F(*cur)
                    if cur is None or exit_data(*cur)[1] > 2:
                        break
                    n += 1
                    if n > 60:
                        break
                box_run[n] = box_run.get(n, 0) + 1
    tot = {k: sum(all_runs[k][0].values()) for k in all_runs}
    for k in range(6):
        out("  %4d   %.5f  %.5f  %.5f  %.5f   box %.5f   ledger %.5f" % (k, *[all_runs[key][0].get(k, 0) / tot[key] for key in ("pos", "sing", "fix", "two")], box_k.get(k, 0) / nbox, 0.75 * 4.0 ** (-k)))
    out("  door run n, fraction over the census door children (pos / sing / fix / two), box states with s <= 2 forward, ledger (1/4)(3/4)^(n-1)")
    totd = {k: sum(all_runs[k][1].values()) for k in all_runs}
    nb = sum(box_run.values())
    for n in range(1, 7):
        out("  %4d   %.5f  %.5f  %.5f  %.5f   box %.5f   ledger %.5f" % (n, *[all_runs[key][1].get(n, 0) / totd[key] for key in ("pos", "sing", "fix", "two")], box_run.get(n, 0) / nb, 0.25 * 0.75 ** (n - 1)))
    means_k = [sum(k * v for k, v in all_runs[key][0].items()) / tot[key] for key in ("pos", "sing", "fix", "two")]
    means_n = [sum(n * v for n, v in all_runs[key][1].items()) / totd[key] for key in ("pos", "sing", "fix", "two")]
    out("  mean own cascade run: pos %.4f sing %.4f fix %.4f two %.4f; box %.4f; ledger 0.3333" % (*means_k, sum(k * v for k, v in box_k.items()) / nbox))
    out("  mean door run: pos %.3f sing %.3f fix %.3f two %.3f; box %.3f; ledger 4.000" % (*means_n, sum(n * v for n, v in box_run.items()) / nb))
    out("  door edges at s=1 : s=2 -- " + "; ".join("%s %.4f : %.4f" % (key, all_runs[key][2][1] / totd[key], all_runs[key][2][2] / totd[key]) for key in ("pos", "sing", "fix", "two")) + "; box %.4f : %.4f; ledger 0.6667 : 0.3333" % (box_s12[1] / (box_s12[1] + box_s12[2]), box_s12[2] / (box_s12[1] + box_s12[2])))
    # the digit-transfer law on 5,000 random negative door edges
    out("  digit transfer (18.7.3) on 5,000 random negative door edges: agreement mod 3^(j+d) gives the same d and the identity; sharpness at j+d-1 with the same d")
    n_agree = n_sharp = n_filtered = n_dead = 0
    dmax = 0
    for _ in range(5000):
        while True:
            y = -rng.randrange(3, 2 ** 60, 2)
            if y % 3 != 0:
                break
        s0 = lowest_branch(y)
        w, d = node_at(y, s0)
        dmax = max(dmax, d)
        j = rng.randrange(1, 7)
        check(w < 0 and is_state(w, d) and d == v3(2 ** s0 * y + 1), "child of door %d" % y)
        if top_dead(w, d):
            n_dead += 1
        ch = [ya for a, ya in doors(w, d)]
        # agreement
        yt = y - 2 * rng.randrange(1, 50) * 3 ** (j + d)
        wt, dt = node_at(yt, s0)
        check(dt == d and mod3(yt) == mod3(y), "same d after agreement mod 3^(j+d) at door %d" % y)
        cht = [ya for a, ya in doors(wt, dt)]
        for a in range(d):
            check((ch[a] - cht[a]) % 3 ** j == 0 and v3(ch[a] - cht[a]) == v3(y - yt) - (d - a), "identity at a = %d, door %d" % (a, y))
            check(v3(ch[a] + 1) == a if a >= 1 else True, "v3(y'_a + 1) = a at door %d" % y)
        n_agree += 1
        # sharpness at j + d - 1 digits, same d
        t = rng.randrange(1, 50)
        if t % 3 == 0:
            t += 1
        ys = y - 2 * t * 3 ** (j + d - 1)
        ws, ds = node_at(ys, s0)
        if ds != d:
            n_filtered += 1
            check(j == 1, "a d-changing lift only at j = 1 (door %d)" % y)
            continue
        chs = [ya for a, ya in doors(ws, ds)]
        check(v3(ch[0] - chs[0]) == j - 1 and (ch[0] - chs[0]) % 3 ** j != 0, "sharp at the top door, door %d" % y)
        for a in range(d):
            check(v3(ch[a] - chs[a]) == v3(y - ys) - (d - a), "identity at the sharp pair, a = %d, door %d" % (a, y))
        n_sharp += 1
    out("  %d agreements, %d sharp pairs, %d filtered (d changed, all at j = 1), %d child top doors dead, largest d %d" % (n_agree, n_sharp, n_filtered, n_dead, dmax))
    # the size census of negative odd x, |x| <= 10^6
    t0 = time.time()
    cnt6 = {"sing": 0, "fix": 0, "two": 0}
    cnt2 = {"sing": 0, "fix": 0, "two": 0}
    for x in range(-3, -10 ** 6 - 1, -2):
        ot = orbit_target(*state_of_odd(x))
        check(ot is not None and ot[0] != "pos", "orbit of x = %d reaches a negative ring" % x)
        cnt6[ot[0]] += 1
        if x > -2 * 10 ** 5:
            cnt2[ot[0]] += 1
    n6 = sum(cnt6.values())
    out("  size census, odd x with -10^6 <= x <= -3 (%d integers; x = -1 is the singular door itself): to -1 %d (%.4f), to the -5 cycle %d (%.4f), to the -17 cycle %d (%.4f), elsewhere 0; %.1f s"
        % (n6, cnt6["sing"], cnt6["sing"] / n6, cnt6["fix"], cnt6["fix"] / n6, cnt6["two"], cnt6["two"] / n6, time.time() - t0))
    out("  the same for -2*10^5 < x <= -3 (%d integers): %d / %d / %d" % (sum(cnt2.values()), cnt2["sing"], cnt2["fix"], cnt2["two"]))
    report("(c)")


